export const AppScopeContext = createContext<AppScope | null>(null);

// Enquanto a tela sai com animação, continua com os dados de quando estava na tela
export function useScreenScope(): AppScope {
  const live = useContext(AppScopeContext);
  if (!live) throw new Error('useScreenScope fora do AppScopeContext');
  const present = useIsPresent();
  const kept = useRef(live);
  if (present) kept.current = live;
  return kept.current;
}

// Para partes que já estão na tela (controles, listas): sempre os dados atuais
export function useAppScope(): AppScope {
  const live = useContext(AppScopeContext);
  if (!live) throw new Error('useAppScope fora do AppScopeContext');
  return live;
}
