const OTHER_LANGUAGE_SINGULAR: Record<SupportedLanguage, string> = {
  pt: 'Outro',
  en: 'Other',
  es: 'Otro',
  ru: 'Другой',
  ar: 'أخرى',
};

const OTHER_LANGUAGE_PLURAL: Record<SupportedLanguage, string> = {
  pt: 'Outros',
  en: 'Others',
  es: 'Otros',
  ru: 'Другие',
  ar: 'أخرى',
};

function stripAccents(str: string): string {
  return (str || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

const LANGUAGE_LOOKUP_MAP: Map<string, AudiobookLanguageEntry> = new Map();

for (const entry of RECOGNIZED_AUDIOBOOK_LANGUAGES) {
  const allKeys = [
    entry.canonicalPt,
    entry.names.pt,
    entry.names.en,
    entry.names.es,
    entry.names.ru,
    entry.names.ar,
    ...entry.aliases,
  ];
  for (const key of allKeys) {
    const lower = key.toLowerCase().trim();
    if (lower && !LANGUAGE_LOOKUP_MAP.has(lower)) {
      LANGUAGE_LOOKUP_MAP.set(lower, entry);
    }
    const stripped = stripAccents(key);
    if (stripped && !LANGUAGE_LOOKUP_MAP.has(stripped)) {
      LANGUAGE_LOOKUP_MAP.set(stripped, entry);
    }
  }
}

export function findRecognizedLanguageEntry(rawLang?: string): AudiobookLanguageEntry | undefined {
  if (!rawLang) return undefined;
  const trimmed = rawLang.trim();
  if (!trimmed) return undefined;
  const lower = trimmed.toLowerCase();
  if (LANGUAGE_LOOKUP_MAP.has(lower)) {
    return LANGUAGE_LOOKUP_MAP.get(lower);
  }
  const stripped = stripAccents(trimmed);
  if (LANGUAGE_LOOKUP_MAP.has(stripped)) {
    return LANGUAGE_LOOKUP_MAP.get(stripped);
  }
  // Support locale codes like pt-BR, en-US, es-MX, zh-CN, etc.
  if (/^[a-z]{2,3}[-_][a-z]{2,4}$/i.test(lower)) {
    const baseCode = lower.split(/[-_]/)[0];
    if (LANGUAGE_LOOKUP_MAP.has(baseCode)) {
      return LANGUAGE_LOOKUP_MAP.get(baseCode);
    }
  }
  return undefined;
}

export function normalizeAudiobookLanguage(rawLang?: string): string | undefined {
  if (!rawLang) return undefined;
  const trimmed = rawLang.trim();
  if (!trimmed) return undefined;
  const norm = trimmed.toLowerCase();
  const stripped = stripAccents(trimmed);
  if (
    norm === 'desconhecido' ||
    norm === 'desconhecida' ||
    norm === 'unknown' ||
    norm === 'desconocido' ||
    norm === 'неизвестно' ||
    norm === 'غير معروف' ||
    stripped === 'audio local'
  ) {
    return undefined;
  }

  const entry = findRecognizedLanguageEntry(trimmed);
  if (entry) {
    return entry.canonicalPt;
  }

  return 'Outro';
}

export function getLanguageDisplayName(lang: string, currentLang: SupportedLanguage = 'pt'): string {
  const canonical = normalizeAudiobookLanguage(lang);
  if (!canonical) return '';
  if (canonical === 'Outro') {
    return OTHER_LANGUAGE_SINGULAR[currentLang] || 'Outro';
  }
  const entry = findRecognizedLanguageEntry(canonical);
  if (entry) {
    return entry.names[currentLang] || entry.canonicalPt;
  }
  return OTHER_LANGUAGE_SINGULAR[currentLang] || 'Outro';
}

export function getLanguageCardName(lang: string, currentLang: SupportedLanguage = 'pt'): string {
  const canonical = normalizeAudiobookLanguage(lang);
  if (!canonical) return '';
  if (canonical === 'Outro') {
    return OTHER_LANGUAGE_PLURAL[currentLang] || 'Outros';
  }
  return getLanguageDisplayName(canonical, currentLang);
}

export function getSystemLanguage(): SupportedLanguage {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') return 'en';
  const navLang = (navigator.language || (navigator.languages && navigator.languages[0]) || '').toLowerCase();
  if (navLang.startsWith('pt')) return 'pt';
  if (navLang.startsWith('es')) return 'es';
  if (navLang.startsWith('ru')) return 'ru';
  if (navLang.startsWith('ar')) return 'ar';
  if (navLang.startsWith('en')) return 'en';
  return 'en';
}

